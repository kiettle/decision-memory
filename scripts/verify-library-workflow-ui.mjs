import assert from "node:assert/strict"

export async function verifyLibraryWorkflowUi({ browser, models, workspace }) {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
  const page = await context.newPage()
  const errors = [], created = [], aiCalls = []
  page.on("pageerror", error => errors.push(error.message))
  page.on("console", message => { if (message.type() === "error" && !message.text().includes("503 (Service Unavailable)")) errors.push(message.text()) })
  page.on("request", request => { if (request.method() === "POST" && /memory-search|check-proposal/.test(request.url())) aiCalls.push(request.postDataJSON()) })
  const base = "http://localhost:5173/#"
  const api = "http://localhost:3011/api"
  const metadata = await (await page.request.get(`${api}/metadata`)).json()
  const prefix = `decision-memory:v1:${encodeURIComponent(metadata.workspace.id)}:${encodeURIComponent(metadata.currentUser.id)}:`
  const draftKey = `${prefix}form-draft:new`
  const viewKey = `${prefix}library-views`
  const primary = () => page.locator("#decision")
  const params = () => Object.fromEntries(new URLSearchParams(page.url().split("?")[1] ?? ""))
  const go = async path => {
    if (page.url() === `${base}${path}`) await page.reload()
    else await page.goto(`${base}${path}`)
    await page.getByRole("heading", { name: path.startsWith("/decisions/new") ? "New Decision" : path.endsWith("/edit") ? "Edit Decision" : "Decision Library", exact: true }).waitFor()
  }
  const restored = async () => {
    await page.getByRole("button", { name: "Restore draft", exact: true }).click()
    await page.getByRole("button", { name: "Restore draft", exact: true }).waitFor({ state: "detached" })
  }
  const saveView = async name => {
    await page.getByRole("region", { name: "Saved library views", exact: true }).getByRole("button", { name: /^(Save view|Save as new)$/ }).click()
    const dialog = page.getByRole("dialog", { name: "Save library view", exact: true })
    await dialog.getByLabel("View name").fill(name)
    await dialog.getByRole("button", { name: "Save view", exact: true }).click()
    return dialog
  }
  try {
    const snapshot = { q: "migration", channel: "platform-decisions", ownerId: metadata.currentUser.id, tag: "storage", status: "DECIDED", appliesTo: "Atlas migration", dateRange: "90", deadline: "ALL", view: "kanban", sort: "DEADLINE" }
    delete snapshot.deadline
    await go(`/?${new URLSearchParams(snapshot)}`)
    assert.equal(await page.title(), "Decision Memory")
    assert.ok((await page.locator("body").innerText()).includes("Decision Library"))
    await (await saveView("My Atlas choices")).waitFor({ state: "detached" })
    await go("/")
    await page.getByRole("combobox", { name: "Saved views", exact: true }).click()
    await page.getByRole("option", { name: "My Atlas choices", exact: true }).click()
    await page.getByRole("button", { name: "Delete saved view My Atlas choices", exact: true }).waitFor()
    assert.deepEqual(params(), snapshot)
    await page.reload()
    await page.getByRole("button", { name: "Delete saved view My Atlas choices", exact: true }).waitFor()
    assert.deepEqual(params(), snapshot)
    const duplicate = await saveView("my atlas choices")
    await duplicate.getByRole("alert").filter({ hasText: "already exists" }).waitFor()
    await duplicate.getByRole("button", { name: "Cancel", exact: true }).click()
    assert.equal(aiCalls.length, 0, "Saving, applying and reloading views never invokes AI")
    const storedViews = await page.evaluate(key => JSON.parse(localStorage.getItem(key)), viewKey)
    assert.equal(storedViews.length, 1)
    assert.deepEqual(Object.keys(storedViews[0]).sort(), ["id", "name", "search"])

    // Browser storage is isolated by both workspace and user.
    for (const changed of [{ ...metadata, workspace: { ...metadata.workspace, id: "other-workspace" } }, { ...metadata, currentUser: { ...metadata.currentUser, id: "other-user" } }]) {
      await page.route("**/api/metadata", route => route.fulfill({ json: changed }))
      await page.reload()
      await page.getByRole("combobox", { name: "Saved views", exact: true }).filter({ hasText: "No saved views yet" }).waitFor()
      await page.unroute("**/api/metadata")
    }
    await page.reload()
    await page.getByRole("button", { name: "Delete saved view My Atlas choices", exact: true }).click()
    assert.deepEqual(params(), snapshot, "Deleting a view does not change current filters")
    assert.deepEqual(await page.evaluate(key => JSON.parse(localStorage.getItem(key)), viewKey), [])

    // Recovery works in both Flat and Kanban. Empty keyword results try local
    // meaning search once per filter set by themselves; Gemini never runs.
    await page.route("**/api/metadata", route => route.fulfill({ json: { ...metadata, features: { ...metadata.features, memorySearch: true } } }))
    await page.route("**/api/decisions/memory-search", route => route.fulfill({ json: { method: "LOCAL", candidateCount: 9, totalCandidateCount: 9, matches: [] } }))
    const nothingSimilar = () => page.getByText("Find by meaning also found nothing similar.", { exact: false })
    await go("/?q=unlikely-workflow-proof&appliesTo=missing-scope&dateRange=7")
    await page.getByRole("heading", { name: "No decisions match these filters", exact: true }).waitFor()
    await nothingSimilar().waitFor()
    assert.equal(aiCalls.length, 1)
    assert.equal(aiCalls[0].method, "LOCAL")
    assert.equal(await page.getByRole("button", { name: "Find by meaning in empty results", exact: true }).count(), 0)
    await page.waitForTimeout(800)
    assert.equal(aiCalls.length, 1, "An empty meaning result is not retried")
    const nextAttempt = page.waitForRequest(request => request.url().endsWith("/memory-search"))
    await page.getByRole("button", { name: "Search all scopes", exact: true }).click()
    assert.deepEqual(params(), { q: "unlikely-workflow-proof", dateRange: "7" })
    assert.equal((await nextAttempt).postDataJSON().method, "LOCAL")
    await nothingSimilar().waitFor()
    await page.getByRole("button", { name: "Remove date filter", exact: true }).click()
    assert.deepEqual(params(), { q: "unlikely-workflow-proof" })
    await go("/?q=unlikely-workflow-proof&view=kanban&sort=DEADLINE")
    await page.getByRole("heading", { name: "No decisions match these filters", exact: true }).waitFor()
    assert.equal(await page.getByRole("region", { name: "Decision Kanban board" }).count(), 0)
    await page.setViewportSize({ width: 390, height: 844 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.screenshot({ path: "/private/tmp/decision-convenience-empty-mobile.png", fullPage: true })
    await page.getByRole("button", { name: "Clear search text", exact: true }).click()
    await page.getByRole("region", { name: "Decision Kanban board" }).waitFor()
    assert.deepEqual(params(), { view: "kanban", sort: "DEADLINE" })
    await page.unroute("**/api/metadata")
    await page.unroute("**/api/decisions/memory-search")

    // Recover full raw form input through navigation and reload, then save.
    await page.setViewportSize({ width: 1440, height: 1000 })
    await go("/decisions/new")
    const callsBeforeDrafts = aiCalls.length
    await primary().fill("Workflow proof pending question")
    await page.getByRole("combobox", { name: "Applies To", exact: true }).fill("Workflow scope, exact")
    await page.getByRole("option", { name: 'Add “Workflow scope, exact”', exact: true }).click()
    await page.keyboard.press("Escape")
    await page.getByLabel("Decide by (optional)").fill("2026-10-23")
    await page.getByText("More details", { exact: true }).click()
    await page.getByLabel("Context", { exact: true }).fill("Synthetic recovery context")
    await page.getByLabel("Tags", { exact: true }).fill("workflow proof, unfinished ")
    await page.getByLabel("Options Considered", { exact: true }).fill("First option\nSecond option ")
    await page.getByRole("button", { name: "Add link", exact: true }).click()
    await page.getByLabel("Related link 1 URL", { exact: true }).fill("https://example.com/recovery")
    await page.getByText("Draft saved in this browser.", { exact: false }).waitFor()
    await page.getByRole("button", { name: "Cancel", exact: true }).click()
    await page.getByRole("heading", { name: "Decision Library", exact: true }).waitFor()
    await page.route("**/api/metadata", route => route.fulfill({ json: { ...metadata, currentUser: { ...metadata.currentUser, id: "other-draft-user" } } }))
    await go("/decisions/new")
    assert.equal(await page.getByRole("button", { name: "Restore draft", exact: true }).count(), 0)
    assert.equal(await primary().inputValue(), "")
    await page.unroute("**/api/metadata")
    await go("/decisions/new")
    await page.getByText("Unfinished draft available in this browser", { exact: true }).waitFor()
    assert.equal(await page.getByRole("button", { name: "Save Decision", exact: true }).isDisabled(), true)
    await restored()
    assert.equal(await primary().inputValue(), "Workflow proof pending question")
    assert.deepEqual(await page.locator('[data-slot="combobox-chip"]').allTextContents(), ["Workflow scope, exact"])
    assert.equal(await page.getByLabel("Decide by (optional)").inputValue(), "2026-10-23")
    await page.getByText("More details", { exact: true }).click()
    assert.equal(await page.getByLabel("Tags", { exact: true }).inputValue(), "workflow proof, unfinished ")
    assert.equal(await page.getByLabel("Options Considered", { exact: true }).inputValue(), "First option\nSecond option ")
    assert.equal(await page.getByLabel("Related link 1 URL", { exact: true }).inputValue(), "https://example.com/recovery")
    await page.getByRole("button", { name: "Already decided", exact: true }).click()
    await primary().fill("Workflow proof recorded choice")
    await page.getByLabel("Why? (optional)", { exact: true }).fill("So the team understands the reason")
    await page.getByText("More details", { exact: true }).click()
    assert.equal(await page.getByLabel("Why? (optional)", { exact: true }).isVisible(), true)
    await page.reload()
    await restored()
    assert.equal(await page.getByLabel("Why? (optional)", { exact: true }).inputValue(), "So the team understands the reason")
    await page.route("**/api/decisions", route => route.request().method() === "POST" ? route.fulfill({ status: 503, json: { error: "Synthetic failed save" } }) : route.continue())
    await page.getByRole("button", { name: "Save Decision", exact: true }).click()
    await page.getByText("Synthetic failed save", { exact: true }).waitFor()
    assert.equal(await primary().inputValue(), "Workflow proof recorded choice")
    await page.reload()
    await restored()
    await page.unroute("**/api/decisions")
    assert.equal(await primary().isEnabled(), true)
    assert.equal(await page.getByRole("button", { name: "Save Decision", exact: true }).isEnabled(), true)
    await page.screenshot({ path: "/private/tmp/decision-convenience-form-desktop.png", fullPage: true })
    const response = page.waitForResponse(r => r.url() === `${api}/decisions` && r.request().method() === "POST")
    await page.getByRole("button", { name: "Save Decision", exact: true }).click()
    const saved = await (await response).json()
    created.push(saved.id)
    await page.getByRole("heading", { name: "Workflow proof recorded choice", exact: true }).waitFor()
    assert.equal(saved.why, "So the team understands the reason")
    assert.equal(await page.evaluate(key => localStorage.getItem(key), draftKey), null)

    // Edit recovery is record-specific and refuses to restore over a newer record.
    await go(`/decisions/${saved.id}/edit`)
    await primary().fill("Unsaved edit choice")
    await page.reload()
    await restored()
    assert.equal(await primary().inputValue(), "Unsaved edit choice")
    await page.getByRole("button", { name: "Cancel", exact: true }).click()
    const fresh = await page.request.put(`${api}/decisions/${saved.id}`, { data: { ...saved, ownerId: saved.owner?.id ?? "", outcome: "Newer server choice", title: "Newer server choice", references: saved.references.map(({ kind, label, url }) => ({ kind, label, url })) } })
    assert.equal(fresh.ok(), true)
    await go(`/decisions/${saved.id}/edit`)
    await page.getByText("The saved decision changed since this draft.", { exact: false }).waitFor()
    assert.equal(await page.getByRole("button", { name: "Restore draft", exact: true }).count(), 0)
    await page.getByText("Review recovered draft", { exact: true }).click()
    assert.match(await page.getByLabel("Recovered draft text").inputValue(), /Unsaved edit choice/)
    await page.getByRole("button", { name: "Discard draft", exact: true }).click()
    assert.equal(await primary().inputValue(), "Newer server choice")
    assert.equal(await primary().isEnabled(), true)

    await go("/decisions/new")
    assert.equal(await primary().inputValue(), "")
    await primary().fill("Discard this unfinished question")
    await page.reload()
    await page.evaluate(() => { Storage.prototype.removeItem = function () { throw new DOMException("Synthetic removal failure", "SecurityError") } })
    await page.getByRole("button", { name: "Discard draft", exact: true }).click()
    await page.getByRole("alert").filter({ hasText: "It is ignored for this visit" }).waitFor()
    assert.equal(await primary().inputValue(), "")
    assert.equal(await primary().isEnabled(), true)
    await page.reload()
    await page.getByRole("button", { name: "Discard draft", exact: true }).click()
    await page.reload()
    assert.equal(await page.getByRole("button", { name: "Restore draft", exact: true }).count(), 0)
    assert.ok(aiCalls.slice(callsBeforeDrafts).every(call => call.method === "LOCAL" && !("proposal" in call)),
      "Draft restoration and saving only run automatic local related lookups, never Gemini or proposal review")

    // Malformed or unavailable browser storage never breaks capture or view use.
    await page.evaluate(key => localStorage.setItem(key, "{broken"), draftKey)
    await page.reload()
    await page.getByRole("alert").filter({ hasText: "Could not read browser storage" }).waitFor()
    assert.equal(await primary().isEnabled(), true)
    await page.evaluate(key => localStorage.removeItem(key), draftKey)
    await page.evaluate(() => {
      Storage.prototype.setItem = function () { throw new DOMException("Synthetic quota failure", "QuotaExceededError") }
    })
    await primary().fill("Storage failure does not prevent typing")
    await page.getByRole("alert").filter({ hasText: "Draft recovery is unavailable" }).waitFor()
    assert.equal(await primary().isEnabled(), true)
    await page.reload()
    await go("/")
    await page.evaluate(() => { Storage.prototype.setItem = function () { throw new DOMException("Synthetic quota failure", "QuotaExceededError") } })
    const failedView = await saveView("Cannot save view")
    await failedView.getByRole("alert").filter({ hasText: "Could not save views" }).waitFor()
    await failedView.getByRole("button", { name: "Cancel", exact: true }).click()
    await page.reload()
    await page.setViewportSize({ width: 390, height: 844 })
    await (await saveView("Mobile library")).waitFor({ state: "detached" })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.screenshot({ path: "/private/tmp/decision-convenience-views-mobile.png", fullPage: true })
    await go("/decisions/new")
    await page.getByRole("button", { name: "Already decided", exact: true }).click()
    assert.equal(await page.getByLabel("Why? (optional)", { exact: true }).isVisible(), true)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.screenshot({ path: "/private/tmp/decision-convenience-form-mobile.png", fullPage: true })
    assert.equal(await page.locator("vite-error-overlay").count(), 0)
    assert.deepEqual(errors, [])
    console.log("Library workflow UI passed: saved views apply/reload/delete/isolation, actionable Flat/Kanban empty results, automatic local meaning fallback, full draft navigation/reload/failed-save recovery, stale edits, discard, storage failures, visible rationale and mobile layout")
  } finally {
    await context.close()
    for (const id of created) await models.Decision.destroy({ where: { id, workspaceId: workspace.id } })
  }
}
